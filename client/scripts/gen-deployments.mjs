// Generates src/deployments/index.ts from whatever <network>.json files the contracts deploy script has copied here.
// Runs before `next dev` / `next build`; with no JSON present it emits an empty registry so the app still builds.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, "..", "src", "deployments");
fs.mkdirSync(dir, { recursive: true });

const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const entries = [];
for (const f of files) {
  try {
    const j = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
    if (j && typeof j.chainId === "number" && j.contracts) entries.push({ file: f, chainId: j.chainId, network: j.network ?? path.basename(f, ".json") });
    else console.warn(`gen-deployments: skipping ${f} (missing chainId/contracts)`);
  } catch (e) {
    console.warn(`gen-deployments: skipping ${f}: ${e.message}`);
  }
}

const lines = [
  "// GENERATED by scripts/gen-deployments.mjs from src/deployments/*.json (written by contracts/scripts/deploy.ts). Do not edit.",
  'import type { Deployment } from "../lib/types";',
  ...entries.map((e, i) => `import d${i} from "./${e.file}";`),
  "",
  "export const deployments: Record<number, Deployment> = {",
  ...entries.map((e, i) => `  ${e.chainId}: d${i} as unknown as Deployment,`),
  "};",
  "",
];
fs.writeFileSync(path.join(dir, "index.ts"), lines.join("\n"));
console.log(`deployments: ${entries.length ? entries.map((e) => `${e.network} (${e.chainId})`).join(", ") : "none found"}`);
